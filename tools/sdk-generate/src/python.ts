import { spawn } from 'node:child_process';
import { createHash } from 'node:crypto';
import { existsSync } from 'node:fs';
import { mkdir, mkdtemp, readdir, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { idempotentOperations, TARGETS } from '#/generate';
import type { Target } from '#/generate';

export const PYTHON_HEADER_MARKER = '# Generated by tools/sdk-generate';

const REQUIREMENTS = 'tools/sdk-generate/requirements.txt';
const GENERATED_ROOT = 'sdks/python/src/odudu/_generated';
const MINIMUM_PYTHON = [3, 11] as const;

// openapi-python-client 0.30.0 writes `import httpx2` (a fork that needs Python
// 3.11), `from typing import Self` and `enum.StrEnum` (both 3.11). The package
// supports 3.10 on `httpx`, so the templates that write any of them are patched
// before the run. A pattern the generator no longer writes stops the run.
const HTTPX: Replacement = ['httpx2', 'httpx'];

type Replacement = readonly [from: string, to: string];

const PATCHES: Record<string, readonly Replacement[]> = {
  'client.py.jinja': [
    HTTPX,
    [
      'from typing import Any, Self\n',
      'from typing import Any\nfrom typing_extensions import Self\n',
    ],
  ],
  'endpoint_macros.py.jinja': [HTTPX],
  'endpoint_module.py.jinja': [HTTPX],
  'types.py.jinja': [HTTPX],
  'str_enum.py.jinja': [
    ['from enum import StrEnum\n', 'from enum import Enum\n'],
    ['(StrEnum)', '(str, Enum)'],
  ],
};

export const PYTHON_TEMPLATES = Object.keys(PATCHES);

// The generator formats its own output with whatever ruff it finds and its
// default rules; fixing the rules and the target keeps the bytes the same on
// every machine and keeps `typing_extensions.Self` from being rewritten to a
// name Python 3.10 does not have.
const CONFIG = `post_hooks:
  - "ruff check . --isolated --fix-only --select E4,E7,E9,F,I --target-version py310"
  - "ruff format . --isolated --target-version py310"
`;

export function patchTemplate(name: string, text: string): string {
  const replacements = PATCHES[name];
  if (replacements === undefined) throw new Error(`${name} has no patches`);
  let patched = text;
  for (const [from, to] of replacements) {
    if (!patched.includes(from)) {
      throw new Error(
        `${name} no longer contains ${from.trim()}: the template patches need a review`,
      );
    }
    patched = patched.replaceAll(from, to);
  }
  return patched;
}

/** The pairs of HTTP method and path template that take an `Idempotency-Key`, as a Python set. */
export function renderPythonIdempotent(documentText: string, source: string): string {
  const header = `${PYTHON_HEADER_MARKER} from ${source}.\n# Do not edit: run \`pnpm sdks:generate\`.\n\n`;
  const declaration = 'IDEMPOTENT_OPERATIONS: frozenset[tuple[str, str]] = frozenset(';
  const operations = idempotentOperations(documentText, source);
  if (operations.length === 0) return `${header}${declaration})\n`;
  const lines = operations
    .map((operation) => {
      const [method, route] = operation.split(' ');
      return `        ("${method ?? ''}", "${route ?? ''}"),`;
    })
    .join('\n');
  return `${header}${declaration}\n    {\n${lines}\n    }\n)\n`;
}

/** The modules of every generated operation, importable from one public module. */
export function renderPythonOperations(name: string, modules: string[], source: string): string {
  const sorted = [...modules].sort();
  const header = `${PYTHON_HEADER_MARKER} from ${source}.\n# Do not edit: run \`pnpm sdks:generate\`.\n\n`;
  const imports = sorted.map((module) => `    ${module},`).join('\n');
  const names = sorted.map((module) => `    "${module}",`).join('\n');
  return (
    `${header}from odudu._generated.${name}.api.default import (\n${imports}\n)\n\n` +
    `__all__ = [\n${names}\n]\n`
  );
}

interface Run {
  code: number;
  output: string;
}

function run(command: string, args: string[], cwd: string, env?: NodeJS.ProcessEnv): Promise<Run> {
  return new Promise((resolve, reject) => {
    const child = spawn(command, args, { cwd, env: { ...process.env, ...env } });
    let output = '';
    child.stdout.on('data', (chunk: Buffer) => {
      output += chunk.toString();
    });
    child.stderr.on('data', (chunk: Buffer) => {
      output += chunk.toString();
    });
    child.on('error', reject);
    child.on('close', (code) => {
      resolve({ code: code ?? 1, output });
    });
  });
}

async function findPython(): Promise<string> {
  const candidates = [
    process.env.ODUDU_SDK_PYTHON,
    'python3.13',
    'python3.12',
    'python3.11',
    'python3',
  ];
  const probe = `import sys; print(int(sys.version_info >= (${MINIMUM_PYTHON.join(', ')})))`;
  for (const candidate of candidates) {
    if (candidate === undefined || candidate === '') continue;
    const result = await run(candidate, ['-c', probe], tmpdir()).catch(() => undefined);
    if (result?.code === 0 && result.output.trim() === '1') return candidate;
  }
  throw new Error(
    `sdks:generate needs Python ${MINIMUM_PYTHON.join('.')} or newer on the PATH (or ODUDU_SDK_PYTHON)`,
  );
}

async function checked(result: Promise<Run>, what: string): Promise<string> {
  const { code, output } = await result;
  if (code !== 0) throw new Error(`${what} failed (exit ${String(code)}):\n${output}`);
  return output;
}

// The generator and its dependencies are installed with hashes from
// requirements.txt into a virtual environment under node_modules/.cache, so
// nothing touches the repository or the machine's Python.
async function ensureEnvironment(root: string): Promise<string> {
  const requirements = await readFile(path.join(root, REQUIREMENTS), 'utf8');
  const python = await findPython();
  const environment = path.join(root, 'node_modules/.cache/sdk-generate-python');
  const stamp = path.join(environment, 'requirements.sha256');
  const wanted = createHash('sha256').update(requirements).update(python).digest('hex');
  const current = existsSync(stamp) ? await readFile(stamp, 'utf8') : '';
  if (current.trim() !== wanted) {
    await rm(environment, { recursive: true, force: true });
    await mkdir(path.dirname(environment), { recursive: true });
    await checked(
      run(python, ['-m', 'venv', environment], root),
      'creating the virtual environment',
    );
    await checked(
      run(
        path.join(environment, 'bin/python'),
        [
          '-m',
          'pip',
          'install',
          '--disable-pip-version-check',
          '--no-input',
          '--quiet',
          '--require-hashes',
          '-r',
          path.join(root, REQUIREMENTS),
        ],
        root,
      ),
      'installing the generator',
    );
    await writeFile(stamp, `${wanted}\n`);
  }
  return environment;
}

export function generatorVersion(requirements: string): string {
  const match = /^openapi-python-client==(\S+) /mu.exec(requirements);
  if (match?.[1] === undefined)
    throw new Error(`${REQUIREMENTS} does not pin openapi-python-client`);
  return match[1];
}

async function writePatchedTemplates(environment: string, destination: string): Promise<void> {
  const where = await checked(
    run(
      path.join(environment, 'bin/python'),
      [
        '-c',
        'import openapi_python_client, os; print(os.path.dirname(openapi_python_client.__file__))',
      ],
      tmpdir(),
    ),
    'locating the generator templates',
  );
  const templates = path.join(where.trim(), 'templates');
  await mkdir(destination, { recursive: true });
  for (const name of PYTHON_TEMPLATES) {
    const text = await readFile(path.join(templates, name), 'utf8');
    await writeFile(path.join(destination, name), patchTemplate(name, text));
  }
}

async function listFiles(directory: string): Promise<string[]> {
  const entries = await readdir(directory, { recursive: true, withFileTypes: true });
  return entries
    .filter((entry) => entry.isFile())
    .map((entry) =>
      path.relative(directory, path.join(entry.parentPath, entry.name)).split(path.sep).join('/'),
    )
    .sort();
}

async function generateTarget(
  target: Target,
  root: string,
  environment: string,
  templates: string,
  version: string,
  outRoot: string,
  warnings: string[],
): Promise<string[]> {
  const documentText = await readFile(path.join(root, target.document), 'utf8');
  const work = await mkdtemp(path.join(tmpdir(), 'sdk-py-gen-'));
  try {
    const output = path.join(work, target.name);
    const config = path.join(work, 'config.yml');
    await writeFile(config, CONFIG);
    const bin = path.join(environment, 'bin');
    const result = await run(
      path.join(bin, 'openapi-python-client'),
      [
        'generate',
        '--path',
        path.join(root, target.document),
        '--meta',
        'none',
        '--output-path',
        output,
        '--config',
        config,
        '--custom-template-path',
        templates,
      ],
      work,
      {
        PATH: `${bin}${path.delimiter}${process.env.PATH ?? ''}`,
        NO_COLOR: '1',
        RUFF_NO_CACHE: 'true',
        COLUMNS: '200',
      },
    );
    if (result.code !== 0) throw new Error(`generating ${target.name} failed:\n${result.output}`);
    for (const line of result.output.split('\n')) {
      if (line.startsWith('WARNING')) warnings.push(`${target.name}: ${line.slice(8).trim()}`);
    }
    const header = `${PYTHON_HEADER_MARKER} from ${target.document} with openapi-python-client ${version}.\n# Do not edit: run \`pnpm sdks:generate\`.\n`;
    const written: string[] = [];
    const destination = path.join(outRoot, target.pythonOutput);
    await rm(destination, { recursive: true, force: true });
    for (const file of await listFiles(output)) {
      const text = await readFile(path.join(output, file), 'utf8');
      if (!file.endsWith('.py'))
        throw new Error(`the generator wrote ${file}, which is not Python`);
      await mkdir(path.dirname(path.join(destination, file)), { recursive: true });
      await writeFile(path.join(destination, file), `${header}${text}`);
      written.push(`${target.pythonOutput}/${file}`);
    }
    const idempotentPath = path.join(outRoot, target.pythonIdempotentOutput);
    await writeFile(idempotentPath, renderPythonIdempotent(documentText, target.document));
    written.push(target.pythonIdempotentOutput);
    const modules = written
      .filter((file) => file.startsWith(`${target.pythonOutput}/api/default/`))
      .map((file) => path.basename(file, '.py'))
      .filter((module) => module !== '__init__');
    const operationsPath = `${GENERATED_ROOT}/${target.name}_operations.py`;
    await writeFile(
      path.join(outRoot, operationsPath),
      renderPythonOperations(target.name, modules, target.document),
    );
    written.push(operationsPath);
    return written;
  } finally {
    await rm(work, { recursive: true, force: true });
  }
}

export interface PythonResult {
  files: string[];
  warnings: string[];
}

/** Writes `sdks/python/src/odudu/_generated` from the OpenAPI documents; nothing in it is hand-written. */
export async function generatePython(root: string, outRoot: string = root): Promise<PythonResult> {
  for (const target of TARGETS) {
    if (!existsSync(path.join(root, target.document))) {
      throw new Error(
        `${target.document} does not exist: run \`pnpm --filter @odudu/docs generate\` first`,
      );
    }
  }
  const version = generatorVersion(await readFile(path.join(root, REQUIREMENTS), 'utf8'));
  const environment = await ensureEnvironment(root);
  const templates = await mkdtemp(path.join(tmpdir(), 'sdk-py-templates-'));
  const files: string[] = [];
  const warnings: string[] = [];
  try {
    await writePatchedTemplates(environment, templates);
    await rm(path.join(outRoot, GENERATED_ROOT), { recursive: true, force: true });
    await mkdir(path.join(outRoot, GENERATED_ROOT), { recursive: true });
    const marker = `${PYTHON_HEADER_MARKER} with openapi-python-client ${version}.\n# Do not edit: run \`pnpm sdks:generate\`.\n`;
    await writeFile(path.join(outRoot, GENERATED_ROOT, '__init__.py'), marker);
    files.push(`${GENERATED_ROOT}/__init__.py`);
    for (const target of TARGETS) {
      files.push(
        ...(await generateTarget(target, root, environment, templates, version, outRoot, warnings)),
      );
    }
  } finally {
    await rm(templates, { recursive: true, force: true });
  }
  return { files: files.sort(), warnings };
}
