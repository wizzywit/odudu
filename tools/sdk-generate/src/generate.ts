import { existsSync } from 'node:fs';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import openapiTS, { astToString } from 'openapi-typescript';
import type { OpenAPI3 } from 'openapi-typescript';
import generatorPackage from 'openapi-typescript/package.json' with { type: 'json' };

export const GENERATED_HEADER_MARKER = '// Generated by tools/sdk-generate';

export interface Target {
  readonly name: string;
  readonly document: string;
  readonly output: string;
}

// A further generator (the Python models) adds its own list beside this one and
// reads the same documents; the TypeScript step does not know about it.
export const TARGETS: readonly Target[] = [
  {
    name: 'admin',
    document: 'apps/docs/static/openapi/admin.json',
    output: 'sdks/admin-client/src/generated/schema.d.ts',
  },
  {
    name: 'me',
    document: 'apps/docs/static/openapi/me.json',
    output: 'sdks/me-client/src/generated/schema.d.ts',
  },
];

function isOpenApi31(value: unknown): value is OpenAPI3 {
  if (typeof value !== 'object' || value === null || !('openapi' in value)) return false;
  return typeof value.openapi === 'string' && /^3\.1(\.|$)/u.test(value.openapi);
}

export async function renderSchema(documentText: string, source: string): Promise<string> {
  const parsed: unknown = JSON.parse(documentText);
  if (!isOpenApi31(parsed)) {
    throw new Error(`${source} is not an OpenAPI 3.1 document`);
  }
  const ast = await openapiTS(parsed, { silent: true });
  const header =
    `${GENERATED_HEADER_MARKER} from ${source} with openapi-typescript ${generatorPackage.version}.\n` +
    '// Do not edit: run `pnpm sdks:generate`.\n';
  return `${header}${astToString(ast)}`;
}

export async function generateAll(root: string, outRoot: string = root): Promise<string[]> {
  const written: string[] = [];
  for (const target of TARGETS) {
    const documentPath = path.join(root, target.document);
    if (!existsSync(documentPath)) {
      throw new Error(
        `${target.document} does not exist: run \`pnpm --filter @odudu/docs generate\` first`,
      );
    }
    const text = await renderSchema(await readFile(documentPath, 'utf8'), target.document);
    const outputPath = path.join(outRoot, target.output);
    await mkdir(path.dirname(outputPath), { recursive: true });
    await writeFile(outputPath, text);
    written.push(target.output);
  }
  return written;
}

if (import.meta.main) {
  const root = path.resolve(import.meta.dirname, '../../..');
  for (const file of await generateAll(root)) console.log(`wrote ${file}`);
}
