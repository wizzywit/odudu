from __future__ import annotations

import importlib
import json
import pkgutil
import re
from pathlib import Path

import pytest

import odudu
from odudu._generated import admin_idempotent, me_idempotent
from odudu._services.idempotency import is_idempotent

ROOT = Path(__file__).resolve().parents[3]
GENERATED = Path(odudu.__file__).parent / "_generated"
DOCUMENTS = ROOT / "apps/docs/static/openapi"
MARKER = "# Generated by tools/sdk-generate"


def test_every_generated_file_carries_the_header_and_nothing_else_is_in_the_directory() -> None:
    files = [p for p in GENERATED.rglob("*") if p.is_file() and "__pycache__" not in p.parts]
    assert len(files) > 100
    for path in files:
        assert path.suffix == ".py", path
        assert path.read_text(encoding="utf-8").startswith(MARKER), path


@pytest.mark.parametrize("name", ["admin", "me"])
def test_every_generated_module_imports(name: str) -> None:
    package = importlib.import_module(f"odudu._generated.{name}")
    count = 0
    for module in pkgutil.walk_packages(package.__path__, f"{package.__name__}."):
        importlib.import_module(module.name)
        count += 1
    assert count > 10


def test_no_generated_module_names_httpx2() -> None:
    for path in GENERATED.rglob("*.py"):
        assert "httpx2" not in path.read_text(encoding="utf-8"), path


def test_the_me_api_has_no_idempotent_operation() -> None:
    assert me_idempotent.IDEMPOTENT_OPERATIONS == frozenset()


def sample(template: str) -> str:
    return re.sub(r"\{[^}]+\}", "x1", template)


@pytest.mark.skipif(not DOCUMENTS.exists(), reason="the OpenAPI documents are generated")
def test_the_matcher_agrees_with_the_document_for_every_admin_operation() -> None:
    document = json.loads((DOCUMENTS / "admin.json").read_text(encoding="utf-8"))
    marked = 0
    for template, item in document["paths"].items():
        for method in item:
            if method.upper() not in {"GET", "POST", "PUT", "PATCH", "DELETE"}:
                continue
            expected = (method.upper(), template) in admin_idempotent.IDEMPOTENT_OPERATIONS
            marked += expected
            got = is_idempotent(
                method.upper(), sample(template), admin_idempotent.IDEMPOTENT_OPERATIONS
            )
            assert got is expected, (method, template)
    assert marked == len(admin_idempotent.IDEMPOTENT_OPERATIONS) == 24


def test_the_matcher_reads_a_path_and_not_a_prefix_or_an_extra_segment() -> None:
    operations = frozenset({("POST", "/t/{tenant}/things/{id}/go")})
    assert is_idempotent("POST", "/t/a/things/7/go", operations)
    assert not is_idempotent("POST", "/t/a/things/7/go/more", operations)
    assert not is_idempotent("POST", "/x/t/a/things/7/go", operations)
    assert not is_idempotent("PUT", "/t/a/things/7/go", operations)
    assert not is_idempotent("POST", "/t/a/things//go", operations)
    assert is_idempotent("post", "/t/a%2Fb/things/7/go", operations)
