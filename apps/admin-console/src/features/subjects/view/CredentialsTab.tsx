import { useId, type ReactNode } from 'react';
import {
  credentialsOf,
  factorLabel,
  lockoutSummary,
  removeFactorLabel,
  type Credential,
  type Lockout,
  type Subject,
} from '#/features/subjects/service.ts';
import {
  useSubjectCredentials,
  type Asking,
  type SubjectCredentials,
} from '#/features/subjects/usecase/useSubjectCredentials.ts';
import { Button } from '#/shared/view/Button.tsx';
import { ConfirmDialog } from '#/shared/view/ConfirmDialog.tsx';
import { DataTable, type Column } from '#/shared/view/DataTable.tsx';
import { EmptyState } from '#/shared/view/EmptyState.tsx';
import { SecretDialog } from '#/shared/view/SecretDialog.tsx';
import { FormSkeleton } from '#/shared/view/Skeleton.tsx';
import { StatusTag } from '#/shared/view/StatusTag.tsx';
import { Timestamp } from '#/shared/view/Timestamp.tsx';
import styles from '#/features/subjects/view/Tab.module.css';

interface TabProps {
  tenant: string;
  subject: Subject;
  etag: string;
  gone: boolean;
  canManage: boolean;
  self: boolean;
}

function Panel({ title, children }: { title: string; children: ReactNode }) {
  const heading = useId();
  return (
    <section aria-labelledby={heading} className={styles.panel}>
      <h2 id={heading} className={styles.heading}>
        {title}
      </h2>
      {children}
    </section>
  );
}

function Failed({ what, retry }: { what: string; retry: () => void }) {
  return (
    <EmptyState
      variant="failed"
      title={`${what} could not be loaded`}
      action={<Button onPress={retry}>Try again</Button>}
    >
      The gateway did not answer, or answered with an error.
    </EmptyState>
  );
}

function Password({
  password,
  page,
  canManage,
}: {
  password: Credential | null;
  page: SubjectCredentials;
  canManage: boolean;
}) {
  return (
    <Panel title="Password">
      <p className={styles.text}>
        {password === null ? (
          `${page.name} has no password yet.`
        ) : (
          <>
            {`Set `}
            <Timestamp value={password.created_at} />
            {password.expired === true ? (
              <>
                {' '}
                <StatusTag tone="warning">expired</StatusTag> It must be changed at the next
                sign-in.
              </>
            ) : null}
          </>
        )}
      </p>
      <p className={styles.rule}>
        Nobody chooses a password here. A one-time password is generated by the server and shown to
        you once; the subject must change it at their next sign-in.
      </p>
      {canManage ? (
        <div className={styles.actions}>
          <Button
            onPress={() => {
              page.ask({ kind: 'password' });
            }}
          >
            Issue a one-time password
          </Button>
        </div>
      ) : null}
    </Panel>
  );
}

function Factors({
  factors,
  page,
  canManage,
}: {
  factors: readonly Credential[];
  page: SubjectCredentials;
  canManage: boolean;
}) {
  const columns: Column<Credential>[] = [
    {
      id: 'type',
      header: 'Factor',
      isRowHeader: true,
      cell: (credential) => factorLabel(credential.type),
    },
    {
      id: 'created_at',
      header: 'Enrolled',
      cell: (credential) => <Timestamp value={credential.created_at} />,
    },
  ];
  if (canManage) {
    columns.push({
      id: 'remove',
      header: 'Action',
      cell: (credential) => (
        <Button
          size="small"
          variant="quiet"
          aria-label={removeFactorLabel(credential)}
          onPress={() => {
            page.ask({ kind: 'factor', credential });
          }}
        >
          Remove
        </Button>
      ),
    });
  }
  return (
    <Panel title="Second factors">
      <DataTable
        label={`Second factors of ${page.name}`}
        columns={columns}
        rows={factors}
        rowKey={(credential) => credential.id ?? credential.type}
        empty={`${page.name} has no authenticator app or passkey enrolled.`}
      />
      <p className={styles.rule}>
        Removing a factor means the next sign-in no longer offers or asks for it. To have one
        enrolled again, require it among the subject&apos;s required actions.
      </p>
    </Panel>
  );
}

function RecoveryCodes({
  count,
  page,
  canManage,
}: {
  count: number | null;
  page: SubjectCredentials;
  canManage: boolean;
}) {
  return (
    <Panel title="Recovery codes">
      <p className={styles.text}>
        {count === null || count === 0
          ? `No recovery codes: ${page.name} holds no unspent one.`
          : count === 1
            ? '1 unspent recovery code'
            : `${String(count)} unspent recovery codes`}
      </p>
      <p className={styles.rule}>
        Codes are shown only to the subject, once, and carry no id of their own, so the set is
        revoked whole or not at all.
      </p>
      {canManage && count !== null && count > 0 ? (
        <div className={styles.actions}>
          <Button
            variant="danger"
            onPress={() => {
              page.ask({ kind: 'recovery-codes' });
            }}
          >
            Revoke every recovery code
          </Button>
        </div>
      ) : null}
    </Panel>
  );
}

function LockoutPanel({
  lockout,
  page,
  canManage,
}: {
  lockout: Lockout;
  page: SubjectCredentials;
  canManage: boolean;
}) {
  const summary = lockoutSummary(lockout);
  return (
    <Panel title="Lockout">
      <p className={styles.text}>
        <StatusTag tone={summary.tone}>{summary.state}</StatusTag> {summary.text}
      </p>
      {lockout.locked_until === null && lockout.last_failure_at === null ? null : (
        <dl className={styles.fixed}>
          {lockout.locked_until === null ? null : (
            <>
              <dt>{lockout.locked ? 'Locked until' : 'Last lock ended'}</dt>
              <dd>
                <Timestamp value={lockout.locked_until} />
              </dd>
            </>
          )}
          {lockout.last_failure_at === null ? null : (
            <>
              <dt>Last failed sign-in</dt>
              <dd>
                <Timestamp value={lockout.last_failure_at} />
              </dd>
            </>
          )}
        </dl>
      )}
      {canManage && lockout.failure_count > 0 ? (
        <div className={styles.actions}>
          <Button
            onPress={() => {
              page.ask({ kind: 'lockout' });
            }}
          >
            Clear the lockout
          </Button>
        </div>
      ) : null}
    </Panel>
  );
}

interface Dialog {
  readonly title: string;
  readonly consequence: string;
  readonly confirmLabel: string;
  readonly tone: 'primary' | 'danger';
}

function dialogOf(asking: Asking, name: string, self: boolean): Dialog {
  switch (asking.kind) {
    case 'password':
      return {
        title: `Issue ${name} a one-time password?`,
        consequence: self
          ? 'This replaces your own password, and you must change it at your next sign-in. Any lockout is cleared. No session ends, this one included.'
          : `This replaces the password ${name} has, and they must change it at their next sign-in. Any lockout is cleared. No session ends and no grant is revoked.`,
        confirmLabel: 'Issue password',
        tone: 'primary',
      };
    case 'factor': {
      const label = factorLabel(asking.credential.type);
      const lowered = `${label.charAt(0).toLowerCase()}${label.slice(1)}`;
      return {
        title: `Remove ${name}’s ${lowered}?`,
        consequence: `${name}'s next sign-in no longer offers or asks for this ${lowered}. Signing in with it again needs a new enrolment.`,
        confirmLabel: 'Remove',
        tone: 'danger',
      };
    }
    case 'recovery-codes':
      return {
        title: `Revoke ${name}’s recovery codes?`,
        consequence: `Every recovery code ${name} holds stops working, unspent ones too. They get a fresh set only when one is asked of them, as the generate-recovery-codes required action.`,
        confirmLabel: 'Revoke recovery codes',
        tone: 'danger',
      };
    case 'lockout':
      return {
        title: `Clear ${name}’s lockout?`,
        consequence: `The run of failed sign-ins is forgotten, so ${name}'s next right password signs in at once, and the next wrong one counts from one.`,
        confirmLabel: 'Clear lockout',
        tone: 'primary',
      };
  }
}

function Held({ page, canManage }: { page: SubjectCredentials; canManage: boolean }) {
  const { credentials, lockout } = page;
  return (
    <>
      {credentials.status === 'loading' ? (
        <FormSkeleton label="Loading credentials" />
      ) : credentials.status === 'failed' ? (
        <Failed what="The credentials" retry={credentials.retry} />
      ) : (
        (() => {
          const held = credentialsOf(credentials.data.items);
          return (
            <>
              <Password password={held.password} page={page} canManage={canManage} />
              <Factors factors={held.factors} page={page} canManage={canManage} />
              <RecoveryCodes count={held.recoveryCodes} page={page} canManage={canManage} />
            </>
          );
        })()
      )}
      {lockout.status === 'loading' ? (
        <FormSkeleton label="Loading the lockout" fields={2} />
      ) : lockout.status === 'failed' ? (
        <Failed what="The lockout" retry={lockout.retry} />
      ) : (
        <LockoutPanel lockout={lockout.data} page={page} canManage={canManage} />
      )}
    </>
  );
}

export function CredentialsTab({ tenant, subject, canManage, self }: TabProps) {
  const page = useSubjectCredentials(tenant, subject);
  const dialog = page.asking === null ? null : dialogOf(page.asking, page.name, self);
  return (
    <div className={styles.tab}>
      {page.itself ? (
        <p className={styles.text}>
          {`A ${subject.type} subject signs in as itself, with its client's credentials: it has no password, second factor, recovery code or lockout.`}
        </p>
      ) : (
        <Held page={page} canManage={canManage} />
      )}
      <ConfirmDialog
        isOpen={dialog !== null}
        title={dialog?.title ?? ''}
        consequence={dialog?.consequence ?? ''}
        confirmLabel={dialog?.confirmLabel ?? ''}
        tone={dialog?.tone ?? 'primary'}
        busy={page.busy}
        problem={page.problem}
        onConfirm={page.confirm}
        onCancel={page.cancel}
      />
      <SecretDialog
        secret={page.secret}
        title={`${page.name}'s one-time password`}
        label="one-time password"
        onClose={page.closeSecret}
      >
        {`Give it to ${page.name} by a channel you trust. They must change it at their next sign-in.`}
      </SecretDialog>
    </div>
  );
}
