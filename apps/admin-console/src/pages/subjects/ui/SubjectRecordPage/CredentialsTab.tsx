import { Link } from 'react-aria-components';
import {
  useSubjectCredentials,
  type SubjectCredentials,
} from '#/pages/subjects/use-cases/useSubjectCredentials';
import {
  useSubjectMail,
  type MailOutcome,
  type SubjectMail,
} from '#/pages/subjects/use-cases/useSubjectMail';
import { Button } from '#/shared/ui/Button';
import { ChecklistField } from '#/shared/ui/ChecklistField';
import { AskedDialog } from '#/shared/ui/ConfirmDialog';
import { DataTable, type Column } from '#/shared/ui/DataTable';
import { LoadFailed } from '#/shared/ui/LoadFailed';
import { LiveMessage } from '#/shared/ui/Message';
import { Panel } from '#/shared/ui/Panel';
import { SecretDialog } from '#/shared/ui/SecretDialog';
import { FormSkeleton } from '#/shared/ui/Skeleton';
import { StatusTag } from '#/shared/ui/StatusTag';
import { Timestamp } from '#/shared/ui/Timestamp';
import { recordTab } from '#/shared/ui/RecordTab';
import type { FactorRow, HeldCredentials } from '#/pages/subjects/services/credentialView';
import type { LockoutView } from '#/pages/subjects/services/lockout';
import { type Subject } from '#/entities/subject';
import { type Credential } from '#/pages/subjects/types/credential';

interface TabProps {
  tenant: string;
  subject: Subject;
  etag: string;
  gone: boolean;
  canManage: boolean;
  self: boolean;
}

function Outcome({ outcome }: { outcome: MailOutcome | null }) {
  return (
    <LiveMessage>
      {outcome === null ? null : (
        <>
          {outcome.text}
          {outcome.fix === null ? null : (
            <>
              {' '}
              <Link href={outcome.fix.href}>{outcome.fix.label}</Link>
            </>
          )}
        </>
      )}
    </LiveMessage>
  );
}

function Password({
  password,
  page,
  mail,
  canManage,
}: {
  password: Credential | null;
  page: SubjectCredentials;
  mail: SubjectMail;
  canManage: boolean;
}) {
  return (
    <Panel title="Password">
      <p className={recordTab.text}>
        {password === null ? (
          `${page.name} has no password yet.`
        ) : (
          <>
            {`Set `}
            <Timestamp value={password.createdAt} />
            {password.expired === true ? (
              <>
                {' '}
                <StatusTag tone="warning">expired</StatusTag> It must be changed at the next
                sign-in.
              </>
            ) : null}
          </>
        )}
      </p>
      <p className={recordTab.rule}>
        Nobody chooses a password here. A reset email lets the subject choose one from their own
        mailbox; a one-time password is generated by the server, shown to you once, and must be
        changed at the next sign-in.
      </p>
      {canManage && mail.email === null ? (
        <p className={recordTab.rule}>
          {`${page.name} has no email address, so no reset link can be sent: a one-time password is the way.`}
        </p>
      ) : null}
      {canManage ? (
        <div className={recordTab.actions}>
          {mail.email === null ? null : (
            <Button variant="primary" isDisabled={mail.reset.busy} onPress={mail.reset.send}>
              Send a password reset email
            </Button>
          )}
          <Button
            onPress={() => {
              page.ask({ kind: 'password' });
            }}
          >
            Issue a one-time password
          </Button>
        </div>
      ) : null}
      <Outcome outcome={mail.reset.outcome} />
    </Panel>
  );
}

function Factors({
  factors,
  page,
  canManage,
}: {
  factors: readonly FactorRow[];
  page: SubjectCredentials;
  canManage: boolean;
}) {
  const columns: Column<FactorRow>[] = [
    {
      id: 'type',
      header: 'Factor',
      isRowHeader: true,
      cell: (factor) => factor.label,
    },
    {
      id: 'created_at',
      header: 'Enrolled',
      cell: (factor) => <Timestamp value={factor.credential.createdAt} />,
    },
  ];
  if (canManage) {
    columns.push({
      id: 'remove',
      header: 'Action',
      cell: (factor) => (
        <Button
          size="small"
          variant="quiet"
          aria-label={factor.removeLabel}
          onPress={() => {
            page.ask(factor.remove);
          }}
        >
          Remove
        </Button>
      ),
    });
  }
  return (
    <Panel title="Second factors">
      <DataTable
        label={`Second factors of ${page.name}`}
        columns={columns}
        rows={factors}
        rowKey={(factor) => factor.credential.id ?? factor.credential.type}
        empty={`${page.name} has no authenticator app or passkey enrolled.`}
      />
      <p className={recordTab.rule}>
        Removing a factor means the next sign-in no longer offers or asks for it. Removing the last
        one also revokes the subject&apos;s recovery codes. To have one enrolled again, require it
        among the subject&apos;s required actions.
      </p>
    </Panel>
  );
}

function RecoveryCodes({
  held,
  page,
  canManage,
}: {
  held: HeldCredentials;
  page: SubjectCredentials;
  canManage: boolean;
}) {
  const count = held.recoveryCodes;
  return (
    <Panel title="Recovery codes">
      <p className={recordTab.text}>{held.recoveryText}</p>
      <p className={recordTab.rule}>
        Codes are shown only to the subject, once, and carry no id of their own, so the set is
        revoked whole or not at all.
      </p>
      {canManage && count !== null && count > 0 ? (
        <div className={recordTab.actions}>
          <Button
            variant="danger"
            onPress={() => {
              page.ask(held.revoke);
            }}
          >
            Revoke every recovery code
          </Button>
        </div>
      ) : null}
    </Panel>
  );
}

function LockoutPanel({
  view: { lockout, summary },
  page,
  canManage,
}: {
  view: LockoutView;
  page: SubjectCredentials;
  canManage: boolean;
}) {
  return (
    <Panel title="Lockout">
      <p className={recordTab.text}>
        <StatusTag tone={summary.tone}>{summary.state}</StatusTag> {summary.text}
      </p>
      {lockout.lockedUntil === null && lockout.lastFailureAt === null ? null : (
        <dl className={recordTab.fixed}>
          {lockout.lockedUntil === null ? null : (
            <>
              <dt>{lockout.locked ? 'Locked until' : 'Last lock ended'}</dt>
              <dd>
                <Timestamp value={lockout.lockedUntil} />
              </dd>
            </>
          )}
          {lockout.lastFailureAt === null ? null : (
            <>
              <dt>Last failed sign-in</dt>
              <dd>
                <Timestamp value={lockout.lastFailureAt} />
              </dd>
            </>
          )}
        </dl>
      )}
      {canManage && lockout.failureCount > 0 ? (
        <div className={recordTab.actions}>
          <Button
            onPress={() => {
              page.ask({ kind: 'lockout' });
            }}
          >
            Clear the lockout
          </Button>
        </div>
      ) : null}
    </Panel>
  );
}

function Email({ name, mail }: { name: string; mail: SubjectMail }) {
  const { actions } = mail;
  if (mail.email === null) {
    return (
      <Panel title="Email">
        <p className={recordTab.rule}>
          {`${name} has no email address, so nothing can be mailed. Add one under Profile.`}
        </p>
      </Panel>
    );
  }
  return (
    <Panel title="Email">
      <p className={recordTab.rule}>
        {`Each link goes to ${mail.email}, and is never shown here. Nothing is sent until the tenant can send mail.`}
      </p>
      <div className={recordTab.actions}>
        <Button isDisabled={mail.verification.busy} onPress={mail.verification.send}>
          Send a verification email
        </Button>
      </div>
      <Outcome outcome={mail.verification.outcome} />
      <form
        noValidate
        className={recordTab.form}
        onSubmit={(event) => {
          event.preventDefault();
          actions.send();
        }}
      >
        <ChecklistField
          label="Required actions to email"
          description="The link takes the subject through these in order. A password is set from the link itself; a factor is enrolled only after signing in."
          options={actions.options}
          value={actions.actions}
          error={actions.errors.actions}
          onChange={actions.choose}
        />
        <div className={recordTab.actions}>
          <Button type="submit" isDisabled={actions.busy}>
            Email required actions
          </Button>
        </div>
      </form>
      <Outcome outcome={actions.outcome} />
    </Panel>
  );
}

function Held({
  page,
  mail,
  canManage,
}: {
  page: SubjectCredentials;
  mail: SubjectMail;
  canManage: boolean;
}) {
  const { credentials, lockout, held, lockoutView } = page;
  return (
    <>
      {held !== null ? (
        <>
          <Password password={held.password} page={page} mail={mail} canManage={canManage} />
          <Factors factors={held.factors} page={page} canManage={canManage} />
          <RecoveryCodes held={held} page={page} canManage={canManage} />
        </>
      ) : credentials.status === 'failed' ? (
        <LoadFailed title="The credentials could not be loaded" retry={credentials.retry} />
      ) : (
        <FormSkeleton label="Loading credentials" />
      )}
      {lockoutView !== null ? (
        <LockoutPanel view={lockoutView} page={page} canManage={canManage} />
      ) : lockout.status === 'failed' ? (
        <LoadFailed title="The lockout could not be loaded" retry={lockout.retry} />
      ) : (
        <FormSkeleton label="Loading the lockout" fields={2} />
      )}
      {canManage ? <Email name={page.name} mail={mail} /> : null}
    </>
  );
}

export function CredentialsTab({ tenant, subject, canManage, self }: TabProps) {
  const page = useSubjectCredentials(tenant, subject, self);
  const mail = useSubjectMail(tenant, subject);
  const { dialog } = page;
  return (
    <div className={recordTab.tab}>
      {page.itself ? (
        <p className={recordTab.text}>
          {`A ${subject.type} subject signs in as itself, with its client's credentials: it has no password, second factor, recovery code or lockout.`}
        </p>
      ) : (
        <Held page={page} mail={mail} canManage={canManage} />
      )}
      <AskedDialog
        asked={dialog}
        busy={page.busy}
        problem={page.problem}
        choice={page.choice}
        onConfirm={page.confirm}
        onCancel={page.cancel}
      />
      <SecretDialog
        secret={page.secret}
        title={`${page.name}'s one-time password`}
        label="one-time password"
        onClose={page.closeSecret}
      >
        {`Give it to ${page.name} by a channel you trust. They must change it at their next sign-in.`}
      </SecretDialog>
    </div>
  );
}
