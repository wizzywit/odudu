import { execFileSync } from 'node:child_process';
import { readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { encodePng, rasteriseMark, MARK_SIZE } from '#/service/mark-png';
import { mailPalette } from '#/service/palette';

const PACKAGE = join(import.meta.dirname, '..');
const SERVICE = join(PACKAGE, 'src/service');
const TOKENS = join(PACKAGE, '../../apps/admin-console/src/shared/ui/tokens.css');
const MARK = join(PACKAGE, '../instrument/src/mark.svg');
const PRETTIER = join(PACKAGE, '../../node_modules/.bin/prettier');

const HEADER =
  '// Generated by packages/email/scripts/generate-assets.ts from the console tokens\n' +
  '// and the Instrument mark. Run `pnpm --filter @odudu/email generate`; do not edit.\n';

const [tokens, svg] = await Promise.all([readFile(TOKENS, 'utf8'), readFile(MARK, 'utf8')]);
const palette = mailPalette(tokens);
const png = encodePng(
  rasteriseMark(svg, {
    background: palette.light.rail,
    ink: palette.light.railInk,
    edge: palette.light.railEdge,
  }),
  MARK_SIZE,
  MARK_SIZE,
);

const files = {
  'palette.generated.ts': `${HEADER}import { type MailPalette } from '#/service/palette';\n\nexport const MAIL_PALETTE: MailPalette = ${JSON.stringify(palette)};\n`,
  'mark.generated.ts': `${HEADER}\nexport const MARK_PNG_BASE64 = '${png.toString('base64')}';\n`,
};
await Promise.all(
  Object.entries(files).map(([name, content]) => writeFile(join(SERVICE, name), content)),
);
execFileSync(PRETTIER, ['--write', ...Object.keys(files).map((name) => join(SERVICE, name))]);
process.stdout.write(`mail assets: palette and a ${String(png.length)}-byte mark\n`);
