// Front-Channel §3 and Back-Channel §2.3's "set of logged-in RPs" for a
// session: enough of each distinct client's logout metadata to build both
// kinds of logout request, none of the rest of its configuration. `clientId`
// is the clients table's own surrogate id — the delivery queue's foreign
// key wants exactly that — while `oauthClientId` is the client_id string a
// Logout Token's `aud` must carry (Back-Channel Logout §2.4); front-channel
// logout needs neither for anything beyond distinguishing rows.
export interface ClientLogoutTarget {
  clientId: string;
  oauthClientId: string;
  frontchannelLogoutUri: string | null;
  frontchannelLogoutSessionRequired: boolean;
  backchannelLogoutUri: string | null;
  backchannelLogoutSessionRequired: boolean;
}

function toRecord(row: typeof tokenGrants.$inferSelect): TokenGrantRecord {
  return {
    id: row.id,
    tenantId: row.tenantId,
    clientId: row.clientId,
    subjectId: row.subjectId,
    scope: row.scope,
    audience: row.audience,
    createdAt: row.createdAt,
    revokedAt: row.revokedAt,
    revokedCause: row.revokedCause,
    sessionId: row.sessionId,
    actorSubjectId: row.actorSubjectId,
    exchangedFromGrantId: row.exchangedFromGrantId,
    actChain: row.actChain,
    expCeiling: row.expCeiling,
    requestedUserinfoClaims: row.requestedUserinfoClaims,
    mayAct: row.mayAct,
    targetTenantId: row.targetTenantId,
  };
}

// Why a grant was revoked, where the path that revoked it knows. Left out, the
// cause is not recorded and the grant is treated as revoked for cause.
export type RevokedCause = 'sign_out' | 'reattached';

export interface NewTokenGrant {
  // Generated by the caller, before the access token is minted, so the
  // same id can be signed into the token's `grant_id` claim
  // (`mintAccessToken`, `token-issuance.ts`) and stored here — the only way
  // introspection or revocation can later name *this* row rather than a
  // sibling that happens to share client, subject and session.
  id: string;
  tenantId: string;
  clientId: string;
  subjectId: string;
  scope: string;
  audience: string[];
  sessionId?: string | null;
  // Both null for every grant this table has ever held before RFC 8693 —
  // present together only on an exchanged grant, which records who acted
  // (the token's own `act.sub`) and which grant it was exchanged from.
  actorSubjectId?: string | null;
  exchangedFromGrantId?: string | null;
  // The `act` claim issued on this grant's own access token, if any — see
  // the column's own comment in schema/token-grants.ts for why the whole
  // chain is kept rather than just `actorSubjectId`.
  actChain?: unknown;
  // The ceiling `mintAccessToken`'s own `expCeiling` applied when this
  // grant was minted, so a refresh rotation can reapply it.
  expCeiling?: Date | null;
  requestedUserinfoClaims?: readonly string[] | null;
  mayAct?: unknown;
  // The tenant an assistant conversation's grant acts in; see the schema.
  targetTenantId?: string | null;
}

// What a front-channel logout page needs of a client; the rest of
// `ClientLogoutTarget` is for back-channel delivery.
export interface FrontChannelTarget {
  frontchannelLogoutUri: string;
  frontchannelLogoutSessionRequired: boolean;
}

// The most grants one cascade statement revokes; a caller past it asks again.
export const CASCADE_CAP = 10_000;

// An agent instance a cascade revoked whose parent it did not also revoke, with
// the number of instances revoked from it down.
export interface RevokedInstanceRoot {
  id: string;
  ownerSubjectId: string;
  agentClientDbId: string;
  agentClient: string;
  depth: number;
  count: number;
}

export interface CascadeResult {
  grants: number;
  instances: number;
  capped: boolean;
  roots: RevokedInstanceRoot[];
}

// One pass also names the grants at its depth limit that have a child, which
// the next pass starts from so a chain of any length is walked to its end.
interface CascadePass extends CascadeResult {
  frontier: string[];
}

interface CascadeRow {
  id: string | null;
  parent_instance_id: string | null;
  owner_subject_id: string | null;
  agent_client_id: string | null;
  client_id: string | null;
  depth: number | null;
}

interface EndedInstance {
  id: string;
  parent: string | null;
  row: CascadeRow;
}

function instanceRoots(rows: readonly CascadeRow[]): RevokedInstanceRoot[] {
  const ended = new Map<string, EndedInstance>();
  for (const row of rows) {
    if (row.id !== null) ended.set(row.id, { id: row.id, parent: row.parent_instance_id, row });
  }
  const below = new Map<string, number>();
  for (const instance of ended.values()) {
    for (let at: string | null = instance.id; at !== null;) {
      below.set(at, (below.get(at) ?? 0) + 1);
      const parent: string | null = ended.get(at)?.parent ?? null;
      at = parent !== null && ended.has(parent) ? parent : null;
    }
  }
  return [...ended.values()]
    .filter((instance) => instance.parent === null || !ended.has(instance.parent))
    .map(({ id, row }) => ({
      id,
      ownerSubjectId: row.owner_subject_id ?? '',
      agentClientDbId: row.agent_client_id ?? '',
      agentClient: row.client_id ?? '',
      depth: row.depth ?? 0,
      count: below.get(id) ?? 1,
    }));
}

// The grant whose counters this one spends: the root named on it, or its own
// when no exchange made it. A grant that was exchanged and names no root has
// none and is refused, as is one whose id matches no grant. An exchanged grant
// from before the column whose parent was deleted before the backfill cannot be
// told from a sign-in's own grant and keeps a budget of its own.
export async function budgetGrantId(tx: TenantScopedDatabase, id: string): Promise<string | null> {
  const rows = await tx
    .select({ root: tokenGrants.budgetGrantId, parent: tokenGrants.exchangedFromGrantId })
    .from(tokenGrants)
    .where(eq(tokenGrants.id, id));
  const row = rows[0];
  if (row === undefined) return null;
  if (row.root !== null) return row.root;
  return row.parent === null ? id : null;
}

// Takes the lineage roots of the grants a revoke starts from (see
// `lockLineageRoots`) before it updates them. At most one row per distinct
// lineage is locked, however many grants the seeds are.
export async function lockLineages(
  tx: TenantScopedDatabase,
  seeds: SQL | undefined,
  held?: Set<string>,
): Promise<void> {
  await lockLineageRoots(
    tx,
    sql`select id from token_grants where ${seeds ?? sql`true`}`,
    undefined,
    held,
  );
}

// The cause a revoke stamps: only on the first revocation, so a grant already
// ended for another reason keeps that one.
function causeOnFirstRevoke(cause: RevokedCause | undefined): { revokedCause?: SQL } {
  return cause === undefined
    ? {}
    : {
        revokedCause: sql`case when ${tokenGrants.revokedAt} is null then ${cause}::text else ${tokenGrants.revokedCause} end`,
      };
}

export function tokenGrantRepository(tx: TenantScopedDatabase) {
  const budgetGrant = (id: string): Promise<string | null> => budgetGrantId(tx, id);
  // The roots this repository has locked, so a later call does not lock them again.
  const heldRoots = new Set<string>();

  // One pass: the grants exchanged from `ids` down to the structural depth,
  // and every agent instance rooted at any of them, revoked by one recursive
  // statement. The first `cap` rows by depth are taken. A node whose grant is
  // revoked and has no live instance is walked through but takes no place in
  // the cap, which is what lets a second call reach what the first left.
  // The lineage's root is already held, so the rows below are taken in id order
  // only to keep each statement's own locking deterministic: grants first, then
  // the live instances, which both updates read from.
  async function pass(ids: readonly string[], at: Date, cap: number): Promise<CascadePass> {
    const stamp = at.toISOString();
    const rows = (await tx.execute(sql`
      with recursive tree(id, depth) as (
        select g.id, 0 from token_grants g
         where g.id = any(array(select value::uuid from jsonb_array_elements_text(${JSON.stringify(ids)}::jsonb)))
        union all
        select c.id, t.depth + 1 from token_grants c join tree t on c.exchanged_from_grant_id = t.id
         where t.depth < ${STRUCTURAL_MAX_DEPTH}
      ),
      pending as (
        select t.id, t.depth from tree t
         where exists (select 1 from token_grants g where g.id = t.id and g.revoked_at is null)
            or exists (select 1 from agent_instances i where i.root_grant_id = t.id and i.revoked_at is null)
         order by t.depth, t.id
         limit ${cap + 1}
      ),
      picked as (select id from pending order by depth, id limit ${cap}),
      locked as (
        select id from token_grants where id = any(array(select id from picked))
         order by id for no key update
      ),
      ended_grants as (
        update token_grants set revoked_at = ${stamp}::timestamptz
         where id = any(array(select id from locked)) and revoked_at is null
        returning id
      ),
      instance_tree(id, depth) as (
        select i.id, 0 from agent_instances i where i.root_grant_id = any(array(select id from locked))
        union all
        select c.id, t.depth + 1 from agent_instances c join instance_tree t on c.parent_instance_id = t.id
         where t.depth < ${STRUCTURAL_MAX_DEPTH}
      ),
      locked_instances as (
        select id from agent_instances where id in (select id from instance_tree)
           and revoked_at is null
         order by id for no key update
      ),
      ended_instances as (
        update agent_instances set revoked_at = ${stamp}::timestamptz
         where id = any(array(select id from locked_instances)) and revoked_at is null
        returning id, parent_instance_id, owner_subject_id, agent_client_id, depth
      )
      select (select count(*) from ended_grants)::int as grants,
             (select count(*) from pending) > ${cap} as capped,
             (select coalesce(jsonb_agg(distinct t.id), '[]'::jsonb) from tree t
               where t.depth = ${STRUCTURAL_MAX_DEPTH}
                 and exists (select 1 from token_grants c where c.exchanged_from_grant_id = t.id)) as frontier,
             coalesce((select jsonb_agg(jsonb_build_object(
                 'id', e.id, 'parent_instance_id', e.parent_instance_id,
                 'owner_subject_id', e.owner_subject_id, 'agent_client_id', e.agent_client_id,
                 'client_id', c.client_id, 'depth', e.depth))
               from ended_instances e left join clients c on c.id = e.agent_client_id), '[]'::jsonb) as ended`)) as unknown as {
      grants: number;
      capped: boolean;
      frontier: string[];
      ended: CascadeRow[];
    }[];
    const row = rows[0];
    const ended = row?.ended ?? [];
    return {
      grants: row?.grants ?? 0,
      instances: ended.length,
      capped: row?.capped ?? false,
      roots: instanceRoots(ended),
      frontier: row?.frontier ?? [],
    };
  }

  // Passes from `ids`, then from the grants each left at its depth limit,
  // until a chain of any length is done or a pass hits the cap.
  async function cascade(ids: readonly string[], at: Date, cap: number): Promise<CascadeResult> {
    const total: CascadeResult = { grants: 0, instances: 0, capped: false, roots: [] };
    if (ids.length === 0) return total;
    for (let seeds = ids; seeds.length > 0;) {
      const next = await pass(seeds, at, cap);
      total.grants += next.grants;
      total.instances += next.instances;
      total.roots.push(...next.roots);
      total.capped = next.capped;
      seeds = next.capped ? [] : next.frontier;
    }
    return total;
  }

  // Takes the roots of `ids`, the rows an update has just ended, then asks
  // `cascade` again until a pass revokes nothing, then writes one audit row for
  // each instance revoked from the top, and answers what the passes revoked in
  // all. The caller has locked the roots of its seeds; a root new since then is
  // the late-root case of spec 5.4. The last pass has a new snapshot, so a child
  // committed while an earlier pass waited is found. A capped pass has revoked
  // something, so the loop ends.
  async function cascadeAll(
    ids: readonly string[],
    at: Date,
  ): Promise<{ grants: number; instances: number }> {
    if (ids.length > 0) {
      await lockLineageRoots(
        tx,
        sql`select value::uuid as id from jsonb_array_elements_text(${JSON.stringify(ids)}::jsonb)`,
        undefined,
        heldRoots,
      );
    }
    const roots: RevokedInstanceRoot[] = [];
    const total = { grants: 0, instances: 0 };
    for (let more = true; more;) {
      const next = await cascade(ids, at, CASCADE_CAP);
      roots.push(...next.roots);
      total.grants += next.grants;
      total.instances += next.instances;
      more = next.capped || next.grants > 0 || next.instances > 0;
    }
    if (roots.length === 0) return total;
    await auditRepository(tx).recordAll(
      roots.map((root) => ({
        eventType: 'agent_identity' as const,
        action: 'agent.instance_revoked' as const,
        outcome: 'allowed' as const,
        actorSubjectId: root.ownerSubjectId,
        actorClientId: root.agentClientDbId,
        resourceType: 'agent_instance',
        resourceId: root.id,
        detail: {
          agent_client: root.agentClient,
          owner: root.ownerSubjectId,
          instance: root.id,
          depth: root.depth,
          count: root.count,
          via: 'cascade' as const,
        },
      })),
    );
    return total;
  }

  // Revokes the live grants any of `actorIds` acted in, and says which. The
  // ids go in as one JSON value, so a long list is no list of parameters. The
  // `order by` fixes the order the ids are picked in, not the order the update
  // locks the rows, which the cascade's own updates do not fix either.
  async function endActorGrants(actorIds: readonly string[], at: Date): Promise<string[]> {
    if (actorIds.length === 0) return [];
    const rows = (await tx.execute(sql`
      update token_grants set revoked_at = ${at.toISOString()}::timestamptz
       where revoked_at is null and id = any(array(
         select g.id from token_grants g
          where g.actor_subject_id = any(array(
                  select value::uuid from jsonb_array_elements_text(${JSON.stringify(actorIds)}::jsonb)))
            and g.revoked_at is null
          order by g.id))
      returning id`)) as unknown as { id: string }[];
    return rows.map((row) => row.id);
  }

  // One read behind both ways of asking for a session's clients, so the
  // join and the `enabled` filter cannot differ between them.
  async function sessionClients(
    sessionId: string,
    only?: { frontChannelOnly: true; limit: number },
  ): Promise<ClientLogoutTarget[]> {
    const query = tx
      .selectDistinct({
        clientId: clientOidcConfig.clientId,
        oauthClientId: clients.clientId,
        frontchannelLogoutUri: clientOidcConfig.frontchannelLogoutUri,
        frontchannelLogoutSessionRequired: clientOidcConfig.frontchannelLogoutSessionRequired,
        backchannelLogoutUri: clientOidcConfig.backchannelLogoutUri,
        backchannelLogoutSessionRequired: clientOidcConfig.backchannelLogoutSessionRequired,
      })
      .from(tokenGrants)
      .innerJoin(clientOidcConfig, eq(clientOidcConfig.clientId, tokenGrants.clientId))
      .innerJoin(clients, eq(clients.id, tokenGrants.clientId))
      .where(
        and(
          eq(tokenGrants.sessionId, sessionId),
          eq(clients.enabled, true),
          only === undefined ? undefined : isNotNull(clientOidcConfig.frontchannelLogoutUri),
        ),
      )
      .$dynamic();
    return only === undefined ? query : query.orderBy(asc(clients.clientId)).limit(only.limit);
  }

  return {
    async create(input: NewTokenGrant): Promise<TokenGrantRecord> {
      const rows = await tx
        .insert(tokenGrants)
        .values({
          id: input.id,
          tenantId: input.tenantId,
          clientId: input.clientId,
          subjectId: input.subjectId,
          scope: input.scope,
          audience: input.audience,
          sessionId: input.sessionId ?? null,
          actorSubjectId: input.actorSubjectId ?? null,
          exchangedFromGrantId: input.exchangedFromGrantId ?? null,
          budgetGrantId:
            input.exchangedFromGrantId == null
              ? null
              : await budgetGrant(input.exchangedFromGrantId),
          actChain: input.actChain ?? null,
          expCeiling: input.expCeiling ?? null,
          requestedUserinfoClaims:
            input.requestedUserinfoClaims == null ? null : [...input.requestedUserinfoClaims],
          mayAct: input.mayAct ?? null,
          targetTenantId: input.targetTenantId ?? null,
        })
        .returning();
      const row = rows[0];
      if (row === undefined) {
        throw new Error('insert into token_grants returned no row');
      }
      return toRecord(row);
    },

    // RFC 6749 §4.1.2: on detected authorization-code reuse, the tokens
    // issued from the first (legitimate) redemption are revoked, not just
    // the replay rejected. True only for the call that revoked it: an
    // already-revoked grant keeps its first `revoked_at`, and its caller
    // writes no second audit row for a revocation that did not happen.
    async revoke(id: string, revokedAt: Date, cause?: RevokedCause): Promise<boolean> {
      await lockLineages(tx, eq(tokenGrants.id, id), heldRoots);
      const rows = await tx
        .update(tokenGrants)
        .set({ revokedAt, revokedCause: cause ?? null })
        .where(and(eq(tokenGrants.id, id), isNull(tokenGrants.revokedAt)))
        .returning({ id: tokenGrants.id });
      await cascadeAll([id], revokedAt);
      return rows.length > 0;
    },

    // Revokes what was exchanged from grants a caller has just revoked
    // itself, and the instances rooted at them, with `cascadeAll`'s audit.
    async revokeBelow(ids: readonly string[], at: Date): Promise<void> {
      await cascadeAll(ids, at);
    },

    // The share lock a derived grant takes on its parent before it is made.
    // A revoke of the parent updates the row and so waits for it, which makes a
    // concurrent revoke either see the child or find the parent already gone.
    async lockLive(id: string): Promise<boolean> {
      const rows = await tx
        .select({ id: tokenGrants.id })
        .from(tokenGrants)
        .where(and(eq(tokenGrants.id, id), isNull(tokenGrants.revokedAt)))
        .for('share');
      return rows.length > 0;
    },

    // Everything exchanged from `ids`, and the agent instances rooted at any
    // of them, one statement for each pass of a chain's depth. `cap` bounds the
    // grants taken; past it the rest is left live and `capped` says so, and the
    // same call made again takes the next of them. The revoke methods use
    // `cascadeAll`, which loops until nothing is left.
    revokeCascade(ids: readonly string[], at: Date, cap = CASCADE_CAP): Promise<CascadeResult> {
      return cascade(ids, at, cap);
    },

    // Spends one call of the grant's write budget: true when the grant was
    // within `limits`, and the count is raised by the same statement, which the
    // row lock serialises, so of any number of calls made at once no more than
    // the limit are told yes. A grant that is missing, revoked or in another
    // tenant is false. A create is also a mutating call.
    async reserveAgentWrite(
      id: string,
      kind: 'mutating' | 'create',
      limits: { readonly mutating: number; readonly creates: number },
    ): Promise<boolean> {
      const create = kind === 'create';
      const root = await budgetGrant(id);
      if (root === null) return false;
      const rows = await tx
        .update(tokenGrants)
        .set({
          agentWrites: sql`${tokenGrants.agentWrites} + 1`,
          agentCreates: sql`${tokenGrants.agentCreates} + ${create ? 1 : 0}`,
        })
        .where(
          and(
            eq(tokenGrants.id, root),
            isNull(tokenGrants.revokedAt),
            lt(tokenGrants.agentWrites, limits.mutating),
            create ? lt(tokenGrants.agentCreates, limits.creates) : undefined,
          ),
        )
        .returning({ id: tokenGrants.id });
      return rows.length > 0;
    },

    // Whether the grant exists in this tenant and has not been revoked, which
    // tells a spent budget from a sign-in that has ended.
    async isLive(id: string): Promise<boolean> {
      const [own, root] = [id, await budgetGrant(id)];
      if (root === null) return false;
      const rows = await tx
        .select({ id: tokenGrants.id })
        .from(tokenGrants)
        .where(and(inArray(tokenGrants.id, [own, root]), isNull(tokenGrants.revokedAt)));
      return rows.length === new Set([own, root]).size;
    },

    // Gives back a call known to have changed nothing, never below none.
    async releaseAgentWrite(id: string, kind: 'mutating' | 'create'): Promise<void> {
      const root = await budgetGrant(id);
      if (root === null) return;
      await tx
        .update(tokenGrants)
        .set({
          agentWrites: sql`greatest(${tokenGrants.agentWrites} - 1, 0)`,
          agentCreates: sql`greatest(${tokenGrants.agentCreates} - ${kind === 'create' ? 1 : 0}, 0)`,
        })
        .where(eq(tokenGrants.id, root));
    },

    async byId(id: string): Promise<TokenGrantRecord | null> {
      const rows = await tx.select().from(tokenGrants).where(eq(tokenGrants.id, id));
      const row = rows[0];
      return row === undefined ? null : toRecord(row);
    },

    // Logout's whole write. Returns how many grants were bound to the session,
    // so a caller can tell a session that had grants from one that had none.
    // `coalesce` keeps the first revocation's timestamp: re-stamping an
    // already-revoked grant would move its reaping window forward every time
    // logout ran again.
    async revokeForSession(
      sessionId: string,
      revokedAt: Date,
      cause?: RevokedCause,
    ): Promise<number> {
      await lockLineages(tx, eq(tokenGrants.sessionId, sessionId), heldRoots);
      const rows = await tx
        .update(tokenGrants)
        .set({
          revokedAt: sql`coalesce(${tokenGrants.revokedAt}, ${revokedAt.toISOString()}::timestamptz)`,
          ...causeOnFirstRevoke(cause),
        })
        .where(eq(tokenGrants.sessionId, sessionId))
        .returning({ id: tokenGrants.id });
      await cascadeAll(
        rows.map((row) => row.id),
        revokedAt,
      );
      return rows.length;
    },

    // `revokeForSession` for many sessions in one statement.
    async revokeForSessions(
      sessionIds: readonly string[],
      revokedAt: Date,
      cause?: RevokedCause,
    ): Promise<number> {
      if (sessionIds.length === 0) return 0;
      await lockLineages(tx, inArray(tokenGrants.sessionId, [...sessionIds]), heldRoots);
      const rows = await tx
        .update(tokenGrants)
        .set({
          revokedAt: sql`coalesce(${tokenGrants.revokedAt}, ${revokedAt.toISOString()}::timestamptz)`,
          ...causeOnFirstRevoke(cause),
        })
        .where(inArray(tokenGrants.sessionId, [...sessionIds]))
        .returning({ id: tokenGrants.id });
      await cascadeAll(
        rows.map((row) => row.id),
        revokedAt,
      );
      return rows.length;
    },

    // The admin API's consent-revoke write: every grant a subject holds
    // against one client, live or offline alike — narrower than
    // `revokeForSession`, which only ever reaches one session's own bound
    // grants. A second revoke matches no rows because of the
    // `isNull(revokedAt)` predicate, so an already-revoked grant keeps its
    // first timestamp and is not counted.
    async revokeForSubjectClient(
      subjectId: string,
      clientId: string,
      revokedAt: Date,
    ): Promise<number> {
      const seeds = and(
        eq(tokenGrants.subjectId, subjectId),
        eq(tokenGrants.clientId, clientId),
        isNull(tokenGrants.revokedAt),
      );
      await lockLineages(tx, seeds, heldRoots);
      const rows = await tx
        .update(tokenGrants)
        .set({ revokedAt })
        .where(seeds)
        .returning({ id: tokenGrants.id });
      await cascadeAll(
        rows.map((row) => row.id),
        revokedAt,
      );
      return rows.length;
    },

    // What a recovered account does to every grant it holds, offline ones
    // included: whoever held a token before the password was reset holds
    // nothing after. An already-revoked grant keeps its first timestamp.
    async revokeForSubject(subjectId: string, revokedAt: Date): Promise<number> {
      const seeds = and(eq(tokenGrants.subjectId, subjectId), isNull(tokenGrants.revokedAt));
      await lockLineages(tx, seeds, heldRoots);
      const rows = await tx
        .update(tokenGrants)
        .set({ revokedAt })
        .where(seeds)
        .returning({ id: tokenGrants.id });
      await cascadeAll(
        rows.map((row) => row.id),
        revokedAt,
      );
      return rows.length;
    },

    // The foreign key on `actor_subject_id` only clears the column when the
    // actor goes, which would leave the delegated token live with its `act`
    // claim intact; a caller that removes an actor revokes what it acted in.
    async revokeForActor(actorSubjectId: string): Promise<number> {
      const seeds = and(
        eq(tokenGrants.actorSubjectId, actorSubjectId),
        isNull(tokenGrants.revokedAt),
      );
      await lockLineages(tx, seeds, heldRoots);
      const rows = await tx
        .update(tokenGrants)
        .set({ revokedAt: sql`now()` })
        .where(seeds)
        .returning({ id: tokenGrants.id });
      await cascadeAll(
        rows.map((row) => row.id),
        new Date(),
      );
      return rows.length;
    },

    // What removing a client or subjects does to the grants about to be deleted
    // with them: the client's own grants, the subjects' and the ones an actor
    // among them acted in, and everything exchanged from any of those, whatever
    // client holds it, which the delete would otherwise leave live and detached.
    async revokeForRemoval(
      removal: { clientId: string | null; subjectIds: readonly string[] },
      at: Date,
    ): Promise<{ grants: number; instances: number }> {
      const ids = JSON.stringify(removal.subjectIds);
      const named = sql`array(select value::uuid from jsonb_array_elements_text(${ids}::jsonb))`;
      const seeds = sql`revoked_at is null and (
        subject_id = any(${named}) or actor_subject_id = any(${named})
        ${removal.clientId === null ? sql`` : sql`or client_id = ${removal.clientId}::uuid`})`;
      await lockLineages(tx, seeds, heldRoots);
      const rows = await tx
        .update(tokenGrants)
        .set({ revokedAt: at })
        .where(seeds)
        .returning({ id: tokenGrants.id });
      const below = await cascadeAll(
        rows.map((row) => row.id),
        at,
      );
      return { grants: rows.length + below.grants, instances: below.instances };
    },

    // `revokeForActor` for many actors, answering what it revoked in all: the
    // grants they acted in and everything exchanged from them, and the agent
    // instances rooted at any of those. An instance the cascade ends is audited
    // as a cascade revocation.
    async revokeForActors(
      actorIds: readonly string[],
      at: Date,
    ): Promise<{ grants: number; instances: number }> {
      if (actorIds.length > 0) {
        await lockLineages(
          tx,
          sql`actor_subject_id = any(array(
            select value::uuid from jsonb_array_elements_text(${JSON.stringify(actorIds)}::jsonb)))
            and revoked_at is null`,
          heldRoots,
        );
      }
      const ended = await endActorGrants(actorIds, at);
      const below = await cascadeAll(ended, at);
      return { grants: ended.length + below.grants, instances: below.instances };
    },

    async bySession(sessionId: string): Promise<TokenGrantRecord[]> {
      const rows = await tx.select().from(tokenGrants).where(eq(tokenGrants.sessionId, sessionId));
      return rows.map(toRecord);
    },

    // Front-Channel §2 and Back-Channel §2.3's "set of logged-in RPs": the
    // distinct clients that hold a grant issued under this session.
    // `token_grants.client_id` and `client_oidc_config.client_id` are both
    // the clients table's surrogate id, never the OAuth client_id string,
    // so the join needs no third table. Filtered to `enabled`, the same way
    // `webOriginAllowed` (client-oidc-config.ts) is.
    async clientsForSession(sessionId: string): Promise<ClientLogoutTarget[]> {
      return sessionClients(sessionId);
    },

    // The clients of `clientsForSession` that registered a front-channel
    // logout URI, in a stable order and at most `limit` of them: the page
    // that frames them is served from one request, so how many it carries
    // is a bound rather than whatever a tenant's session accumulated.
    async frontChannelClientsForSession(
      sessionId: string,
      limit: number,
    ): Promise<FrontChannelTarget[]> {
      const rows = await sessionClients(sessionId, { frontChannelOnly: true, limit });
      return rows.flatMap((row) =>
        row.frontchannelLogoutUri === null
          ? []
          : [
              {
                frontchannelLogoutUri: row.frontchannelLogoutUri,
                frontchannelLogoutSessionRequired: row.frontchannelLogoutSessionRequired,
              },
            ],
      );
    },

    // The batched form of `clientsForSession`, one round trip for a whole
    // page of sessions rather than one per session — what an admin session
    // listing folds its `client_ids` column through, keyed back to the
    // session each row came from.
    async clientsForSessions(
      sessionIds: readonly string[],
    ): Promise<(ClientLogoutTarget & { sessionId: string })[]> {
      if (sessionIds.length === 0) return [];
      const rows = await tx
        .selectDistinct({
          sessionId: tokenGrants.sessionId,
          clientId: clientOidcConfig.clientId,
          oauthClientId: clients.clientId,
          frontchannelLogoutUri: clientOidcConfig.frontchannelLogoutUri,
          frontchannelLogoutSessionRequired: clientOidcConfig.frontchannelLogoutSessionRequired,
          backchannelLogoutUri: clientOidcConfig.backchannelLogoutUri,
          backchannelLogoutSessionRequired: clientOidcConfig.backchannelLogoutSessionRequired,
        })
        .from(tokenGrants)
        .innerJoin(clientOidcConfig, eq(clientOidcConfig.clientId, tokenGrants.clientId))
        .innerJoin(clients, eq(clients.id, tokenGrants.clientId))
        .where(and(inArray(tokenGrants.sessionId, [...sessionIds]), eq(clients.enabled, true)));
      // `sessionId` is nullable on the column (a client_credentials grant
      // has none) — never on a row that matched the `inArray` above, since
      // every id it was built from is a real session's, but the filter
      // still narrows the type honestly rather than asserting it.
      return rows.filter(
        (row): row is typeof row & { sessionId: string } => row.sessionId !== null,
      );
    },
  };
}
