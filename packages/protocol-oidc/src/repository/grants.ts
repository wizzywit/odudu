import { type TenantScopedDatabase } from '@odudu/db';
import { clients } from '@odudu/domain-tenant';
import { and, asc, eq, inArray, isNotNull, isNull, lt, sql } from 'drizzle-orm';
import { clientOidcConfig } from '#/schema/client-oidc-config';
import { tokenGrants, type TokenGrantRecord } from '#/schema/token-grants';

export type { TokenGrantRecord } from '#/schema/token-grants';

// Front-Channel §3 and Back-Channel §2.3's "set of logged-in RPs" for a
// session: enough of each distinct client's logout metadata to build both
// kinds of logout request, none of the rest of its configuration. `clientId`
// is the clients table's own surrogate id — the delivery queue's foreign
// key wants exactly that — while `oauthClientId` is the client_id string a
// Logout Token's `aud` must carry (Back-Channel Logout §2.4); front-channel
// logout needs neither for anything beyond distinguishing rows.
export interface ClientLogoutTarget {
  clientId: string;
  oauthClientId: string;
  frontchannelLogoutUri: string | null;
  frontchannelLogoutSessionRequired: boolean;
  backchannelLogoutUri: string | null;
  backchannelLogoutSessionRequired: boolean;
}

function toRecord(row: typeof tokenGrants.$inferSelect): TokenGrantRecord {
  return {
    id: row.id,
    tenantId: row.tenantId,
    clientId: row.clientId,
    subjectId: row.subjectId,
    scope: row.scope,
    audience: row.audience,
    createdAt: row.createdAt,
    revokedAt: row.revokedAt,
    sessionId: row.sessionId,
    actorSubjectId: row.actorSubjectId,
    exchangedFromGrantId: row.exchangedFromGrantId,
    actChain: row.actChain,
    expCeiling: row.expCeiling,
    requestedUserinfoClaims: row.requestedUserinfoClaims,
  };
}

export interface NewTokenGrant {
  // Generated by the caller, before the access token is minted, so the
  // same id can be signed into the token's `grant_id` claim
  // (`mintAccessToken`, `token-issuance.ts`) and stored here — the only way
  // introspection or revocation can later name *this* row rather than a
  // sibling that happens to share client, subject and session.
  id: string;
  tenantId: string;
  clientId: string;
  subjectId: string;
  scope: string;
  audience: string[];
  sessionId?: string | null;
  // Both null for every grant this table has ever held before RFC 8693 —
  // present together only on an exchanged grant, which records who acted
  // (the token's own `act.sub`) and which grant it was exchanged from.
  actorSubjectId?: string | null;
  exchangedFromGrantId?: string | null;
  // The `act` claim issued on this grant's own access token, if any — see
  // the column's own comment in schema/token-grants.ts for why the whole
  // chain is kept rather than just `actorSubjectId`.
  actChain?: unknown;
  // The ceiling `mintAccessToken`'s own `expCeiling` applied when this
  // grant was minted, so a refresh rotation can reapply it.
  expCeiling?: Date | null;
  requestedUserinfoClaims?: readonly string[] | null;
}

// What a front-channel logout page needs of a client; the rest of
// `ClientLogoutTarget` is for back-channel delivery.
export interface FrontChannelTarget {
  frontchannelLogoutUri: string;
  frontchannelLogoutSessionRequired: boolean;
}

// How far up the grants exchanged from one another a budget is looked for.
const EXCHANGE_DEPTH = 16;

export function tokenGrantRepository(tx: TenantScopedDatabase) {
  // A grant exchanged from another has that grant's agent write budget, so
  // exchanging an exhausted token does not renew it: only a new sign-in does,
  // and that makes a grant with no parent.
  async function budgetGrant(id: string): Promise<string> {
    let current = id;
    for (let hop = 0; hop < EXCHANGE_DEPTH; hop += 1) {
      const rows = await tx
        .select({ parent: tokenGrants.exchangedFromGrantId })
        .from(tokenGrants)
        .where(eq(tokenGrants.id, current));
      const parent = rows[0]?.parent;
      if (parent === null || parent === undefined) return current;
      current = parent;
    }
    return current;
  }

  // One read behind both ways of asking for a session's clients, so the
  // join and the `enabled` filter cannot differ between them.
  async function sessionClients(
    sessionId: string,
    only?: { frontChannelOnly: true; limit: number },
  ): Promise<ClientLogoutTarget[]> {
    const query = tx
      .selectDistinct({
        clientId: clientOidcConfig.clientId,
        oauthClientId: clients.clientId,
        frontchannelLogoutUri: clientOidcConfig.frontchannelLogoutUri,
        frontchannelLogoutSessionRequired: clientOidcConfig.frontchannelLogoutSessionRequired,
        backchannelLogoutUri: clientOidcConfig.backchannelLogoutUri,
        backchannelLogoutSessionRequired: clientOidcConfig.backchannelLogoutSessionRequired,
      })
      .from(tokenGrants)
      .innerJoin(clientOidcConfig, eq(clientOidcConfig.clientId, tokenGrants.clientId))
      .innerJoin(clients, eq(clients.id, tokenGrants.clientId))
      .where(
        and(
          eq(tokenGrants.sessionId, sessionId),
          eq(clients.enabled, true),
          only === undefined ? undefined : isNotNull(clientOidcConfig.frontchannelLogoutUri),
        ),
      )
      .$dynamic();
    return only === undefined ? query : query.orderBy(asc(clients.clientId)).limit(only.limit);
  }

  return {
    async create(input: NewTokenGrant): Promise<TokenGrantRecord> {
      const rows = await tx
        .insert(tokenGrants)
        .values({
          id: input.id,
          tenantId: input.tenantId,
          clientId: input.clientId,
          subjectId: input.subjectId,
          scope: input.scope,
          audience: input.audience,
          sessionId: input.sessionId ?? null,
          actorSubjectId: input.actorSubjectId ?? null,
          exchangedFromGrantId: input.exchangedFromGrantId ?? null,
          actChain: input.actChain ?? null,
          expCeiling: input.expCeiling ?? null,
          requestedUserinfoClaims:
            input.requestedUserinfoClaims == null ? null : [...input.requestedUserinfoClaims],
        })
        .returning();
      const row = rows[0];
      if (row === undefined) {
        throw new Error('insert into token_grants returned no row');
      }
      return toRecord(row);
    },

    // RFC 6749 §4.1.2: on detected authorization-code reuse, the tokens
    // issued from the first (legitimate) redemption are revoked, not just
    // the replay rejected. True only for the call that revoked it: an
    // already-revoked grant keeps its first `revoked_at`, and its caller
    // writes no second audit row for a revocation that did not happen.
    async revoke(id: string, revokedAt: Date): Promise<boolean> {
      const rows = await tx
        .update(tokenGrants)
        .set({ revokedAt })
        .where(and(eq(tokenGrants.id, id), isNull(tokenGrants.revokedAt)))
        .returning({ id: tokenGrants.id });
      return rows.length > 0;
    },

    // Spends one call of the grant's write budget: true when the grant was
    // within `limits`, and the count is raised by the same statement, which the
    // row lock serialises, so of any number of calls made at once no more than
    // the limit are told yes. A grant that is missing, revoked or in another
    // tenant is false. A create is also a mutating call.
    async reserveAgentWrite(
      id: string,
      kind: 'mutating' | 'create',
      limits: { readonly mutating: number; readonly creates: number },
    ): Promise<boolean> {
      const create = kind === 'create';
      const root = await budgetGrant(id);
      const rows = await tx
        .update(tokenGrants)
        .set({
          agentWrites: sql`${tokenGrants.agentWrites} + 1`,
          agentCreates: sql`${tokenGrants.agentCreates} + ${create ? 1 : 0}`,
        })
        .where(
          and(
            eq(tokenGrants.id, root),
            isNull(tokenGrants.revokedAt),
            lt(tokenGrants.agentWrites, limits.mutating),
            create ? lt(tokenGrants.agentCreates, limits.creates) : undefined,
          ),
        )
        .returning({ id: tokenGrants.id });
      return rows.length > 0;
    },

    // Whether the grant exists in this tenant and has not been revoked, which
    // tells a spent budget from a sign-in that has ended.
    async isLive(id: string): Promise<boolean> {
      const [own, root] = [id, await budgetGrant(id)];
      const rows = await tx
        .select({ id: tokenGrants.id })
        .from(tokenGrants)
        .where(and(inArray(tokenGrants.id, [own, root]), isNull(tokenGrants.revokedAt)));
      return rows.length === new Set([own, root]).size;
    },

    // Gives back a call known to have changed nothing, never below none.
    async releaseAgentWrite(id: string, kind: 'mutating' | 'create'): Promise<void> {
      await tx
        .update(tokenGrants)
        .set({
          agentWrites: sql`greatest(${tokenGrants.agentWrites} - 1, 0)`,
          agentCreates: sql`greatest(${tokenGrants.agentCreates} - ${kind === 'create' ? 1 : 0}, 0)`,
        })
        .where(eq(tokenGrants.id, await budgetGrant(id)));
    },

    async byId(id: string): Promise<TokenGrantRecord | null> {
      const rows = await tx.select().from(tokenGrants).where(eq(tokenGrants.id, id));
      const row = rows[0];
      return row === undefined ? null : toRecord(row);
    },

    // Logout's whole write. Returns the number revoked so a caller can tell
    // "ended a session that had grants" from "ended one that had none"
    // without a second query.
    //
    // `coalesce` keeps the first revocation's timestamp: re-stamping an
    // already-revoked grant at a later `now` would move its reaping window
    // forward every time logout ran again.
    async revokeForSession(sessionId: string, revokedAt: Date): Promise<number> {
      const rows = await tx
        .update(tokenGrants)
        .set({
          revokedAt: sql`coalesce(${tokenGrants.revokedAt}, ${revokedAt.toISOString()}::timestamptz)`,
        })
        .where(eq(tokenGrants.sessionId, sessionId))
        .returning({ id: tokenGrants.id });
      return rows.length;
    },

    // `revokeForSession` for many sessions in one statement.
    async revokeForSessions(sessionIds: readonly string[], revokedAt: Date): Promise<number> {
      if (sessionIds.length === 0) return 0;
      const rows = await tx
        .update(tokenGrants)
        .set({
          revokedAt: sql`coalesce(${tokenGrants.revokedAt}, ${revokedAt.toISOString()}::timestamptz)`,
        })
        .where(inArray(tokenGrants.sessionId, [...sessionIds]))
        .returning({ id: tokenGrants.id });
      return rows.length;
    },

    // The admin API's consent-revoke write: every grant a subject holds
    // against one client, live or offline alike — narrower than
    // `revokeForSession`, which only ever reaches one session's own bound
    // grants. A second revoke matches no rows because of the
    // `isNull(revokedAt)` predicate, so an already-revoked grant keeps its
    // first timestamp and is not counted.
    async revokeForSubjectClient(
      subjectId: string,
      clientId: string,
      revokedAt: Date,
    ): Promise<number> {
      const rows = await tx
        .update(tokenGrants)
        .set({ revokedAt })
        .where(
          and(
            eq(tokenGrants.subjectId, subjectId),
            eq(tokenGrants.clientId, clientId),
            isNull(tokenGrants.revokedAt),
          ),
        )
        .returning({ id: tokenGrants.id });
      return rows.length;
    },

    // What a recovered account does to every grant it holds, offline ones
    // included: whoever held a token before the password was reset holds
    // nothing after. An already-revoked grant keeps its first timestamp.
    async revokeForSubject(subjectId: string, revokedAt: Date): Promise<number> {
      const rows = await tx
        .update(tokenGrants)
        .set({ revokedAt })
        .where(and(eq(tokenGrants.subjectId, subjectId), isNull(tokenGrants.revokedAt)))
        .returning({ id: tokenGrants.id });
      return rows.length;
    },

    // The foreign key on `actor_subject_id` only clears the column when the
    // actor goes, which would leave the delegated token live with its `act`
    // claim intact; a caller that removes an actor revokes what it acted in.
    async revokeForActor(actorSubjectId: string): Promise<number> {
      const rows = await tx
        .update(tokenGrants)
        .set({ revokedAt: sql`now()` })
        .where(and(eq(tokenGrants.actorSubjectId, actorSubjectId), isNull(tokenGrants.revokedAt)))
        .returning({ id: tokenGrants.id });
      return rows.length;
    },

    async bySession(sessionId: string): Promise<TokenGrantRecord[]> {
      const rows = await tx.select().from(tokenGrants).where(eq(tokenGrants.sessionId, sessionId));
      return rows.map(toRecord);
    },

    // Front-Channel §2 and Back-Channel §2.3's "set of logged-in RPs": the
    // distinct clients that hold a grant issued under this session.
    // `token_grants.client_id` and `client_oidc_config.client_id` are both
    // the clients table's surrogate id, never the OAuth client_id string,
    // so the join needs no third table. Filtered to `enabled`, the same way
    // `webOriginAllowed` (client-oidc-config.ts) is.
    async clientsForSession(sessionId: string): Promise<ClientLogoutTarget[]> {
      return sessionClients(sessionId);
    },

    // The clients of `clientsForSession` that registered a front-channel
    // logout URI, in a stable order and at most `limit` of them: the page
    // that frames them is served from one request, so how many it carries
    // is a bound rather than whatever a tenant's session accumulated.
    async frontChannelClientsForSession(
      sessionId: string,
      limit: number,
    ): Promise<FrontChannelTarget[]> {
      const rows = await sessionClients(sessionId, { frontChannelOnly: true, limit });
      return rows.flatMap((row) =>
        row.frontchannelLogoutUri === null
          ? []
          : [
              {
                frontchannelLogoutUri: row.frontchannelLogoutUri,
                frontchannelLogoutSessionRequired: row.frontchannelLogoutSessionRequired,
              },
            ],
      );
    },

    // The batched form of `clientsForSession`, one round trip for a whole
    // page of sessions rather than one per session — what an admin session
    // listing folds its `client_ids` column through, keyed back to the
    // session each row came from.
    async clientsForSessions(
      sessionIds: readonly string[],
    ): Promise<(ClientLogoutTarget & { sessionId: string })[]> {
      if (sessionIds.length === 0) return [];
      const rows = await tx
        .selectDistinct({
          sessionId: tokenGrants.sessionId,
          clientId: clientOidcConfig.clientId,
          oauthClientId: clients.clientId,
          frontchannelLogoutUri: clientOidcConfig.frontchannelLogoutUri,
          frontchannelLogoutSessionRequired: clientOidcConfig.frontchannelLogoutSessionRequired,
          backchannelLogoutUri: clientOidcConfig.backchannelLogoutUri,
          backchannelLogoutSessionRequired: clientOidcConfig.backchannelLogoutSessionRequired,
        })
        .from(tokenGrants)
        .innerJoin(clientOidcConfig, eq(clientOidcConfig.clientId, tokenGrants.clientId))
        .innerJoin(clients, eq(clients.id, tokenGrants.clientId))
        .where(and(inArray(tokenGrants.sessionId, [...sessionIds]), eq(clients.enabled, true)));
      // `sessionId` is nullable on the column (a client_credentials grant
      // has none) — never on a row that matched the `inArray` above, since
      // every id it was built from is a real session's, but the filter
      // still narrows the type honestly rather than asserting it.
      return rows.filter(
        (row): row is typeof row & { sessionId: string } => row.sessionId !== null,
      );
    },
  };
}
